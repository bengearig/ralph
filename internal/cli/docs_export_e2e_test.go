const exportNotice = "> Generated by ralph from document %s (version %d). Do not edit this file: the next export overwrites it. Change the document through ralph instead.\n"

func exportedFile(id string, version int, title, kind, brief, body string) string {
	var b strings.Builder
	b.WriteString("<!-- ralph:generated document=" + id + " version=" + strconv.Itoa(version) + " -->\n")
	b.WriteString("# " + title + "\n\n")
	b.WriteString(fmt.Sprintf(exportNotice, id, version) + "\n")
	b.WriteString("- Kind: " + kind + "\n")
	if brief != "" {
		b.WriteString("- Brief: " + brief + "\n")
	}
	b.WriteString("\n" + body + "\n")
	return b.String()
}

func (e *e2eEnv) commitAll(t *testing.T, message string) {
	t.Helper()
	e.repo.Commit(message)
}

func (e *e2eEnv) gitStatus(t *testing.T) string {
	t.Helper()
	return e.repo.Git("status", "--short", "-uall")
}

func (e *e2eEnv) exportPath(rel string) string {
	return filepath.Join(e.dir, "docs", "ralph", rel)
}

func (e *e2eEnv) readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func (e *e2eEnv) wantFile(t *testing.T, rel, want string) {
	t.Helper()
	if got := e.readFile(t, e.exportPath(rel)); got != want {
		t.Errorf("%s =\n%q\nwant\n%q", rel, got, want)
	}
}

func (e *e2eEnv) wantMissing(t *testing.T, rel string) {
	t.Helper()
	if _, err := os.Lstat(e.exportPath(rel)); !os.IsNotExist(err) {
		t.Errorf("%s exists (err %v), want it removed", rel, err)
	}
}

func (e *e2eEnv) wantRun(t *testing.T, code int, args ...string) e2eRun {
	t.Helper()
	r := e.run(t, args...)
	if r.code != code {
		t.Fatalf("ralph %v exit = %d, want %d\nstdout: %s\nstderr: %s", args, r.code, code, r.stdout, r.stderr)
	}
	return r
}

func e2eDocFingerprint(t *testing.T, cs *mcp.ClientSession, id string) string {
	t.Helper()
	return e2eOK(t, cs, "doc_get", map[string]any{"id": id})["fingerprint"].(string)
}

func e2eDocUpdate(t *testing.T, cs *mcp.ClientSession, id string, fields map[string]any) {
	t.Helper()
	args := map[string]any{"id": id, "fingerprint": e2eDocFingerprint(t, cs, id)}
	for k, v := range fields {
		args[k] = v
	}
	e2eOK(t, cs, "doc_update", args)
}

func e2eDocStatus(t *testing.T, cs *mcp.ClientSession, tool, id string, extra map[string]any) {
	t.Helper()
	args := map[string]any{"id": id, "fingerprint": e2eDocFingerprint(t, cs, id)}
	for k, v := range extra {
		args[k] = v
	}
	e2eOK(t, cs, tool, args)
}

func exportListing(dir string) (map[string]time.Time, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	out := map[string]time.Time{}
	for _, ent := range entries {
		info, err := ent.Info()
		if err != nil {
			return nil, err
		}
		out[ent.Name()] = info.ModTime()
	}
	return out, nil
}

// exportedProject returns an initialized, committed project holding a brief
// (B-1), a project-wide document (D-1) and a document tied to the brief (D-2).
func exportedProject(t *testing.T) (*e2eEnv, *mcp.ClientSession) {
	t.Helper()
	e := newE2EEnv(t)
	e.init(t)
	e.commitAll(t, "ralph init")
	cs := e.connect(t, io.Discard)
	e2eOK(t, cs, "unit_create", map[string]any{"level": "brief", "title": "Ship it", "body": "Please ship it."})
	e2eOK(t, cs, "doc_create", map[string]any{"kind": "architecture", "title": "Overview", "body": "The shape."})
	e2eOK(t, cs, "doc_create", map[string]any{"kind": "decision", "title": "Pick a Store", "body": "We pick SQLite.\n\nIt is simple.", "brief_id": "B-1"})
	return e, cs
}

func TestE2EDocsExportFlow(t *testing.T) {
	e, cs := exportedProject(t)
	baseline := e.gitStatus(t)

	r := e.wantRun(t, 0, "docs", "export")
	for _, want := range []string{"created docs/ralph/D-1-overview.md", "created docs/ralph/D-2-pick-a-store.md", "exported: created 2, updated 0, removed 0, unchanged 0"} {
		if !strings.Contains(r.stdout, want) {
			t.Errorf("first export output lacks %q:\n%s", want, r.stdout)
		}
	}
	e.wantFile(t, "D-1-overview.md", exportedFile("D-1", 1, "Overview", "architecture", "", "The shape."))
	e.wantFile(t, "D-2-pick-a-store.md", exportedFile("D-2", 1, "Pick a Store", "decision", "B-1 Ship it", "We pick SQLite.\n\nIt is simple."))

	wantStatus := strings.TrimSpace(baseline + "\n?? docs/ralph/D-1-overview.md\n?? docs/ralph/D-2-pick-a-store.md")
	if got := e.gitStatus(t); got != wantStatus {
		t.Errorf("git status after export =\n%s\nwant\n%s", got, wantStatus)
	}

	before, err := exportListing(e.exportPath(""))
	if err != nil {
		t.Fatal(err)
	}
	time.Sleep(50 * time.Millisecond)
	r = e.wantRun(t, 0, "docs", "export")
	if r.stdout != "exported: created 0, updated 0, removed 0, unchanged 2\n" {
		t.Errorf("second export output = %q", r.stdout)
	}
	after, err := exportListing(e.exportPath(""))
	if err != nil {
		t.Fatal(err)
	}
	if len(after) != len(before) {
		t.Errorf("files after second export = %v, before %v", after, before)
	}
	for name, mt := range before {
		if !after[name].Equal(mt) {
			t.Errorf("%s modification time changed from %v to %v", name, mt, after[name])
		}
	}

	r = e.wantRun(t, 0, "docs", "export", "--check")
	if strings.TrimSpace(r.stdout) != "up to date" {
		t.Errorf("--check output = %q", r.stdout)
	}
	_ = cs
}

func TestE2EDocsExportFollowsChanges(t *testing.T) {
	e, cs := exportedProject(t)
	e.wantRun(t, 0, "docs", "export")

	checkOutOfStep := func(label string, wants ...string) {
		t.Helper()
		before, err := exportListing(e.exportPath(""))
		if err != nil {
			t.Fatal(err)
		}
		r := e.wantRun(t, 1, "docs", "export", "--check")
		for _, w := range wants {
			if !strings.Contains(r.stdout, w) {
				t.Errorf("%s: --check output lacks %q:\n%s", label, w, r.stdout)
			}
		}
		after, err := exportListing(e.exportPath(""))
		if err != nil {
			t.Fatal(err)
		}
		if len(before) != len(after) {
			t.Errorf("%s: --check changed the files: %v -> %v", label, before, after)
		}
		for n, mt := range before {
			if !after[n].Equal(mt) {
				t.Errorf("%s: --check touched %s", label, n)
			}
		}
	}
	exportAndCheck := func(label string, wants ...string) {
		t.Helper()
		r := e.wantRun(t, 0, "docs", "export")
		for _, w := range wants {
			if !strings.Contains(r.stdout, w) {
				t.Errorf("%s: export output lacks %q:\n%s", label, w, r.stdout)
			}
		}
		e.wantRun(t, 0, "docs", "export", "--check")
	}

	e2eDocUpdate(t, cs, "D-1", map[string]any{"body": "The new shape."})
	checkOutOfStep("body edit", "would update docs/ralph/D-1-overview.md")
	exportAndCheck("body edit", "updated docs/ralph/D-1-overview.md", "updated 1")
	e.wantFile(t, "D-1-overview.md", exportedFile("D-1", 2, "Overview", "architecture", "", "The new shape."))

	e2eDocUpdate(t, cs, "D-1", map[string]any{"title": "System Overview"})
	checkOutOfStep("rename", "would remove docs/ralph/D-1-overview.md", "would create docs/ralph/D-1-system-overview.md")
	r := e.wantRun(t, 0, "docs", "export")
	if strings.Count(r.stdout, "removed docs/ralph/D-1-overview.md") != 1 || strings.Count(r.stdout, "created docs/ralph/D-1-system-overview.md") != 1 {
		t.Errorf("rename export output:\n%s", r.stdout)
	}
	e.wantMissing(t, "D-1-overview.md")
	e.wantFile(t, "D-1-system-overview.md", exportedFile("D-1", 3, "System Overview", "architecture", "", "The new shape."))
	e.wantRun(t, 0, "docs", "export", "--check")

	edited := e.exportPath("D-2-pick-a-store.md")
	if err := os.WriteFile(edited, []byte("<!-- ralph:generated document=D-2 version=1 -->\nhand edited\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	checkOutOfStep("hand edit", "would update docs/ralph/D-2-pick-a-store.md")
	exportAndCheck("hand edit", "updated docs/ralph/D-2-pick-a-store.md")
	e.wantFile(t, "D-2-pick-a-store.md", exportedFile("D-2", 1, "Pick a Store", "decision", "B-1 Ship it", "We pick SQLite.\n\nIt is simple."))

	e2eDocStatus(t, cs, "doc_archive", "D-2", nil)
	checkOutOfStep("archive", "would remove docs/ralph/D-2-pick-a-store.md")
	exportAndCheck("archive", "removed docs/ralph/D-2-pick-a-store.md")
	e.wantMissing(t, "D-2-pick-a-store.md")

	e2eDocStatus(t, cs, "doc_restore", "D-2", nil)
	checkOutOfStep("restore", "would create docs/ralph/D-2-pick-a-store.md")
	exportAndCheck("restore", "created docs/ralph/D-2-pick-a-store.md")
	e.wantFile(t, "D-2-pick-a-store.md", exportedFile("D-2", 1, "Pick a Store", "decision", "B-1 Ship it", "We pick SQLite.\n\nIt is simple."))

	e2eDocStatus(t, cs, "doc_supersede", "D-2", map[string]any{"superseded_by": "D-1"})
	checkOutOfStep("supersede", "would remove docs/ralph/D-2-pick-a-store.md")
	exportAndCheck("supersede", "removed docs/ralph/D-2-pick-a-store.md")
	e.wantMissing(t, "D-2-pick-a-store.md")
	e.wantFile(t, "D-1-system-overview.md", exportedFile("D-1", 3, "System Overview", "architecture", "", "The new shape."))
}

func TestE2EDocsExportNeverTouchesOthersFiles(t *testing.T) {
	e, _ := exportedProject(t)
	hand := map[string]string{
		"README.md":              "# Hand written\n",
		"D-7-notes.md":           "my notes, no marker\n",
		"D-2-pick-a-store.md":    "I wrote this by hand.\n",
		"nested/D-9-anything.md": "<!-- ralph:generated document=D-9 version=1 -->\nnot at the top level\n",
	}
	for rel, content := range hand {
		e.repo.WriteFile(filepath.Join("docs", "ralph", rel), content)
	}

	for _, args := range [][]string{{"docs", "export"}, {"docs", "export"}, {"docs", "export", "--check"}} {
		r := e.wantRun(t, 1, args...)
		if !strings.Contains(r.stdout, "conflict docs/ralph/D-2-pick-a-store.md") {
			t.Errorf("%v output lacks the conflict:\n%s", args, r.stdout)
		}
		for rel, content := range hand {
			if got := e.readFile(t, e.exportPath(rel)); got != content {
				t.Errorf("%v changed %s to %q", args, rel, got)
			}
		}
	}
	e.wantFile(t, "D-1-overview.md", exportedFile("D-1", 1, "Overview", "architecture", "", "The shape."))

	r := e.wantRun(t, 1, "docs", "export", "--json")
	var got struct {
		Unchanged int `json:"unchanged"`
		Conflicts []struct {
			Path string `json:"path"`
			ID   string `json:"id"`
		} `json:"conflicts"`
	}
	if err := json.Unmarshal([]byte(r.stdout), &got); err != nil {
		t.Fatalf("--json output: %v\n%s", err, r.stdout)
	}
	if len(got.Conflicts) != 1 || got.Conflicts[0].Path != "docs/ralph/D-2-pick-a-store.md" || got.Conflicts[0].ID != "D-2" || got.Unchanged != 1 {
		t.Errorf("--json = %+v", got)
	}
}

func TestE2EDocsExportSettingAndRefusals(t *testing.T) {
	t.Run("moves the output", func(t *testing.T) {
		e, _ := exportedProject(t)
		e.appendProject(t, "documents:\n  export:\n    dir: exports/docs\n")
		e.wantRun(t, 0, "docs", "export")
		for name, want := range map[string]string{
			"D-1-overview.md":     exportedFile("D-1", 1, "Overview", "architecture", "", "The shape."),
			"D-2-pick-a-store.md": exportedFile("D-2", 1, "Pick a Store", "decision", "B-1 Ship it", "We pick SQLite.\n\nIt is simple."),
		} {
			if got := e.readFile(t, filepath.Join(e.dir, "exports", "docs", name)); got != want {
				t.Errorf("%s = %q", name, got)
			}
		}
		if _, err := os.Lstat(filepath.Join(e.dir, "docs")); !os.IsNotExist(err) {
			t.Errorf("default directory was created (err %v)", err)
		}
	})

	t.Run("refused settings", func(t *testing.T) {
		for _, dir := range []string{"..", "/tmp/x", ".git", ".ralph/x"} {
			e, _ := exportedProject(t)
			e.appendProject(t, "documents:\n  export:\n    dir: "+dir+"\n")
			for _, args := range [][]string{{"status"}, {"docs", "export"}, {"docs", "export", "--check"}, {"mcp"}} {
				r := e.wantRun(t, 1, args...)
				if !strings.Contains(r.stderr, "invalid configuration") || !strings.Contains(r.stderr, "documents.export.dir") {
					t.Errorf("dir %q, ralph %v stderr = %q", dir, args, r.stderr)
				}
			}
			if _, err := os.Lstat(filepath.Join(e.dir, "docs")); !os.IsNotExist(err) {
				t.Errorf("dir %q: default directory was created", dir)
			}
		}
	})

	t.Run("symlink out of the repository", func(t *testing.T) {
		e, _ := exportedProject(t)
		outside := t.TempDir()
		if err := os.Symlink(outside, filepath.Join(e.dir, "docs")); err != nil {
			t.Skipf("symlinks unavailable: %v", err)
		}
		r := e.wantRun(t, 1, "docs", "export")
		if !strings.Contains(r.stderr, "documents.export.dir") || !strings.Contains(r.stderr, "not inside the project") {
			t.Errorf("stderr = %q", r.stderr)
		}
		entries, err := os.ReadDir(outside)
		if err != nil {
			t.Fatal(err)
		}
		if len(entries) != 0 {
			t.Errorf("files written outside the repository: %v", entries)
		}
	})
}

func (e *e2eEnv) appendProject(t *testing.T, yaml string) {
	t.Helper()
	path := filepath.Join(e.dir, ".ralph", "project.yaml")
	existing, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(existing, []byte(yaml)...), 0o644); err != nil {
		t.Fatal(err)
	}
}

func TestE2EDocsExportCommittedFilesReview(t *testing.T) {
	e, cs := exportedProject(t)
	e.wantRun(t, 0, "docs", "export")
	e.repo.Git("add", "docs/ralph")
	e.repo.Git("commit", "-m", "export documents")

	e2eDocUpdate(t, cs, "D-1", map[string]any{"body": "The shape, now with a unique sentence."})
	e.wantRun(t, 0, "docs", "export")

	if got := e.repo.Git("diff", "--name-only"); got != "docs/ralph/D-1-overview.md" {
		t.Fatalf("changed files = %q", got)
	}
	diff := e.repo.Git("diff")
	for _, want := range []string{"+The shape, now with a unique sentence.", "-The shape.", "-<!-- ralph:generated document=D-1 version=1 -->", "+<!-- ralph:generated document=D-1 version=2 -->"} {
		if !strings.Contains(diff, want) {
			t.Errorf("diff lacks %q:\n%s", want, diff)
		}
	}
	if n := strings.Count(diff, "\n"); n > 25 {
		t.Errorf("diff is %d lines, want it small:\n%s", n, diff)
	}
	for _, banned := range []string{"Test User", "test@example.com"} {
		if strings.Contains(diff, banned) {
			t.Errorf("diff contains %q:\n%s", banned, diff)
		}
	}
	if regexp.MustCompile(`\d{4}-\d{2}-\d{2}`).MatchString(diff) {
		t.Errorf("diff contains a date:\n%s", diff)
	}
	changed := e.repo.Git("diff", "--stat")
	if strings.Contains(changed, "D-2") {
		t.Errorf("unchanged document appears in the diff:\n%s", changed)
	}
}

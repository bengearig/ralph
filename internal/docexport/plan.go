package docexport

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"path/filepath"
	"sort"
	"syscall"

	"github.com/bengearig/ralph/internal/documents"
	"github.com/bengearig/ralph/internal/units"
)

// Action is what an export does to one file.
type Action string

const (
	ActionCreated   Action = "created"
	ActionUpdated   Action = "updated"
	ActionRemoved   Action = "removed"
	ActionUnchanged Action = "unchanged"
	ActionConflict  Action = "conflict"
)

const (
	detailNotGenerated = "exists and was not generated by ralph; not overwritten"
	detailNotRegular   = "exists and is not a regular file"
	markerReadLimit    = 512
)

// Change is one file's planned or applied outcome; ID is the document's ID.
type Change struct {
	Name   string
	ID     string
	Action Action
	Detail string
}

// Plan lists what exporting into Dir would do.
type Plan struct {
	Dir     string
	Changes []Change

	contents map[string][]byte
}

// Result counts what Apply did and returns the conflicts it left alone.
type Result struct {
	Created, Updated, Removed, Unchanged int
	Conflicts                            []Change
}

// BuildPlan compares the active documents with the files in dir and writes nothing.
func BuildPlan(ctx context.Context, docs documents.Service, us units.Service, dir string) (Plan, error) {
	list, err := docs.List(ctx, documents.Filter{})
	if err != nil {
		return Plan{}, fmt.Errorf("list documents: %w", err)
	}
	entries, err := readEntries(dir)
	if err != nil {
		return Plan{}, err
	}
	plan := Plan{Dir: dir, contents: map[string][]byte{}}
	planned := map[string]bool{}
	briefTitles := map[string]string{}
	for _, doc := range list {
		in := Input{ID: doc.ID, Version: doc.Version, Kind: doc.Kind, Title: doc.Title, Body: doc.Body, BriefID: doc.BriefID}
		if doc.BriefID != "" {
			title, ok := briefTitles[doc.BriefID]
			if !ok {
				brief, err := us.Get(ctx, doc.BriefID)
				if err != nil {
					return Plan{}, fmt.Errorf("document %s: read brief %s: %w", doc.ID, doc.BriefID, err)
				}
				title = brief.Title
				briefTitles[doc.BriefID] = title
			}
			in.BriefTitle = title
		}
		name := FileName(doc.ID, doc.Title)
		content := Render(in)
		planned[name] = true
		change := Change{Name: name, ID: doc.ID}
		entry, exists := entries[name]
		switch {
		case !exists:
			change.Action = ActionCreated
		case !entry.Type().IsRegular():
			change.Action, change.Detail = ActionConflict, detailNotRegular
		default:
			existing, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				return Plan{}, fmt.Errorf("read %s: %w", filepath.Join(dir, name), err)
			}
			_, marked := ParseMarker(existing)
			switch {
			case bytes.Equal(existing, content):
				change.Action = ActionUnchanged
			case marked:
				change.Action = ActionUpdated
			default:
				change.Action, change.Detail = ActionConflict, detailNotGenerated
			}
		}
		if change.Action == ActionCreated || change.Action == ActionUpdated {
			plan.contents[name] = content
		}
		plan.Changes = append(plan.Changes, change)
	}
	for name, entry := range entries {
		if planned[name] || !entry.Type().IsRegular() || !OwnedName(name) {
			continue
		}
		info, ok, err := readMarker(filepath.Join(dir, name))
		if err != nil {
			return Plan{}, err
		}
		if ok {
			plan.Changes = append(plan.Changes, Change{Name: name, ID: info.ID, Action: ActionRemoved})
		}
	}
	sort.Slice(plan.Changes, func(i, j int) bool { return plan.Changes[i].Name < plan.Changes[j].Name })
	return plan, nil
}

func readEntries(dir string) (map[string]fs.DirEntry, error) {
	list, err := os.ReadDir(dir)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return nil, nil
		}
		return nil, fmt.Errorf("read export directory %s: %w", dir, err)
	}
	entries := make(map[string]fs.DirEntry, len(list))
	for _, e := range list {
		entries[e.Name()] = e
	}
	return entries, nil
}

func readMarker(path string) (MarkerInfo, bool, error) {
	f, err := os.OpenFile(path, os.O_RDONLY|syscall.O_NOFOLLOW, 0)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return MarkerInfo{}, false, nil
		}
		return MarkerInfo{}, false, fmt.Errorf("open %s: %w", path, err)
	}
	defer func() { _ = f.Close() }()
	buf := make([]byte, markerReadLimit)
	n, err := io.ReadFull(f, buf)
	if err != nil && !errors.Is(err, io.EOF) && !errors.Is(err, io.ErrUnexpectedEOF) {
		return MarkerInfo{}, false, fmt.Errorf("read %s: %w", path, err)
	}
	info, ok := ParseMarker(buf[:n])
	return info, ok, nil
}

// Package docexport renders documents as exported files and recognises the files it owns.
package docexport

import (
	"fmt"
	"regexp"
	"strings"

	"github.com/bengearig/ralph/internal/documents"
	"github.com/bengearig/ralph/internal/naming"
)

// Input is everything an exported file shows; it carries no actor, time or fingerprint.
type Input struct {
	ID         string
	Version    int
	Kind       documents.Kind
	Title      string
	Body       string
	BriefID    string
	BriefTitle string
}

var ownedPattern = regexp.MustCompile(`^D-[0-9]+-[^/\\]*\.md$`)

// Render returns the exact bytes of the exported file for in.
func Render(in Input) []byte {
	var b strings.Builder
	b.WriteString(Marker(in.ID, in.Version))
	b.WriteString("\n# ")
	b.WriteString(strings.TrimSpace(in.Title))
	b.WriteString("\n\n")
	fmt.Fprintf(&b, "> Generated by ralph from document %s (version %d). Do not edit this file: the next export overwrites it. Change the document through ralph instead.\n\n", in.ID, in.Version)
	fmt.Fprintf(&b, "- Kind: %s\n", in.Kind)
	if in.BriefID != "" {
		fmt.Fprintf(&b, "- Brief: %s %s\n", in.BriefID, in.BriefTitle)
	}
	b.WriteString("\n")
	body := strings.ReplaceAll(in.Body, "\r\n", "\n")
	body = strings.ReplaceAll(body, "\r", "\n")
	b.WriteString(strings.TrimRight(body, " \t\n"))
	b.WriteString("\n")
	return []byte(b.String())
}

// FileName returns the base name of the file a document is exported to.
func FileName(id, title string) string {
	return id + "-" + naming.Slugify(title) + ".md"
}

// OwnedName reports whether a base name has the form export gives its files.
func OwnedName(name string) bool {
	return ownedPattern.MatchString(name)
}

func TestRenderEndsWithSingleNewline(t *testing.T) {
	for _, body := range []string{"x", "x\n", "x\n\n\n", "x \t\r\n\r\n", ""} {
		out := Render(Input{ID: "D-1", Version: 1, Kind: documents.KindDesign, Title: "T", Body: body})
		if !bytes.HasSuffix(out, []byte("\n")) {
			t.Fatalf("body %q: no trailing newline", body)
		}
		if body != "" && bytes.HasSuffix(out, []byte("\n\n")) {
			t.Fatalf("body %q: more than one trailing newline", body)
		}
	}
	out := Render(Input{ID: "D-1", Version: 1, Kind: documents.KindDesign, Title: "T"})
	if !strings.HasSuffix(string(out), "- Kind: design\n\n\n") {
		t.Fatalf("empty body: %q", out)
	}
}


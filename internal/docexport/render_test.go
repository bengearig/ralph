func TestParseMarkerRejects(t *testing.T) {
	m := Marker("D-3", 5)
	tests := map[string]string{
		"not on the first line": "# Title\n" + m + "\n",
		"leading blank line":    "\n" + m + "\n",
		"leading space":         " " + m + "\n",
		"missing version":       "<!-- ralph:generated document=D-3 -->\n",
		"non-numeric version":   "<!-- ralph:generated document=D-3 version=x -->\n",
		"task id":               "<!-- ralph:generated document=T-3 version=5 -->\n",
		"lowercase id":          "<!-- ralph:generated document=d-3 version=5 -->\n",
		"id without digits":     "<!-- ralph:generated document=D- version=5 -->\n",
		"text before":           "x " + m + "\n",
		"text after":            m + " x\n",
		"trailing space":        m + " \n",
		"bare marker":           "<!-- ralph:generated -->\n",
		"empty":                 "",
	}
	for name, content := range tests {
		t.Run(name, func(t *testing.T) {
			if info, ok := ParseMarker([]byte(content)); ok {
				t.Fatalf("accepted %q as %+v", content, info)
			}
		})
	}
}

func TestParseMarkerAcceptsCRLFFirstLine(t *testing.T) {
	info, ok := ParseMarker([]byte(Marker("D-3", 5) + "\r\n# T\r\n"))
	if !ok || info != (MarkerInfo{ID: "D-3", Version: 5}) {
		t.Fatalf("got %+v, %v", info, ok)
	}
	if _, ok := ParseMarker([]byte(Marker("D-3", 5))); !ok {
		t.Fatal("marker without newline rejected")
	}
}

func TestFileNameUsesSlug(t *testing.T) {
	tests := []struct{ id, title, want string }{
		{"D-3", "Pull requests and naming", "D-3-pull-requests-and-naming.md"},
		{"D-3", "!!! ???", "D-3-work.md"},
		{"D-8", "alpha beta gamma delta epsilon zeta eta theta iota", "D-8-alpha-beta-gamma-delta-epsilon-zeta-eta.md"},
	}
	for _, tt := range tests {
		if got := FileName(tt.id, tt.title); got != tt.want {
			t.Errorf("FileName(%q, %q) = %q, want %q", tt.id, tt.title, got, tt.want)
		}
	}
}


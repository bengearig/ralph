func TestRenderContainsNoTimeActorOrFingerprint(t *testing.T) {
	const email = "person@example.com"
	doc := documents.Document{ID: "D-1", Kind: documents.KindDesign, Title: "T", Body: "b", Version: 1}
	_ = email // the source record's creator is not an Input field, so it cannot reach the output
	out := string(Render(Input{ID: doc.ID, Version: doc.Version, Kind: doc.Kind, Title: doc.Title, Body: doc.Body}))
	if strings.Contains(out, email) || strings.Contains(out, "@") {
		t.Fatalf("output contains an actor: %q", out)
	}
	if regexp.MustCompile(`\d{4}-\d{2}-\d{2}|\d{2}:\d{2}`).MatchString(out) {
		t.Fatalf("output contains a timestamp: %q", out)
	}
}

